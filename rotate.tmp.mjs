import { chromium } from '@playwright/test'
const b = await chromium.launch()
const page = await b.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://localhost:5200/The-Global-Pulse/?debug')
await page.waitForSelector('.app-root.ready', { timeout: 60000 })
await page.waitForTimeout(7000)
const before = await page.evaluate(() => window.__globeDebug())
await page.mouse.click(720, 430)
await page.waitForTimeout(500)
const afterGlobe = await page.evaluate(() => window.__globeDebug())
await page.mouse.click(150, 120)
await page.waitForTimeout(500)
const afterSpace = await page.evaluate(() => window.__globeDebug())
console.log('lastGlobeClick delta:', await page.evaluate(() => Date.now() - (window.__lastGlobeClick || 0)))
console.log(JSON.stringify({ before, afterGlobe, afterSpace }))
await b.close()
